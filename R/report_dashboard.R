#' Generate an interactive HERVariumR dashboard
#'
#' Generates an HTML dashboard from either a HERVarium_annotation or
#' HERVarium_comparison object.
#'
#' @param x A HERVarium_annotation or HERVarium_comparison object.
#' @param output_dir Output directory.
#' @param report_file Name of the HTML report.
#' @param title Report title.
#' @param top_n Number of top features to show in dashboard plots.
#' @param self_contained Whether to produce a self-contained HTML file.
#'
#' @return Invisibly returns the path to the generated HTML dashboard.
#' @export

generate_hervarium_dashboard <- function(x,
                                         output_dir = NULL,
                                         report_file = NULL,
                                         title = NULL,
                                         top_n = 25,
                                         self_contained = TRUE) {
  
  if (!requireNamespace("rmarkdown", quietly = TRUE)) {
    stop("Package 'rmarkdown' is required. Install it with install.packages('rmarkdown').")
  }
  
  if (!requireNamespace("DT", quietly = TRUE)) {
    stop("Package 'DT' is required. Install it with install.packages('DT').")
  }
  
  if (!requireNamespace("plotly", quietly = TRUE)) {
    stop("Package 'plotly' is required. Install it with install.packages('plotly').")
  }
  
  if (!requireNamespace("ggplot2", quietly = TRUE)) {
    stop("Package 'ggplot2' is required. Install it with install.packages('ggplot2').")
  }
  
  if (!inherits(x, "HERVarium_comparison") &&
      !inherits(x, "HERVarium_annotation")) {
    stop("x must be a HERVarium_comparison or HERVarium_annotation object.")
  }
  
  if (is.null(output_dir)) {
    output_dir <- x$output_dir
  }
  
  if (is.null(output_dir)) {
    stop("Please provide output_dir or use an object with output_dir.")
  }
  
  if (!dir.exists(output_dir)) {
    dir.create(output_dir, recursive = TRUE)
  }
  
  object_type <- if (inherits(x, "HERVarium_comparison")) {
    "comparison"
  } else {
    "annotation"
  }
  
  if (is.null(report_file)) {
    report_file <- if (object_type == "comparison") {
      "hervarium_comparison_dashboard.html"
    } else {
      "hervarium_annotation_dashboard.html"
    }
  }
  
  if (is.null(title)) {
    title <- if (object_type == "comparison") {
      paste0("HERVariumR comparison dashboard: ",
             x$foreground_name, " vs ", x$background_name)
    } else {
      "HERVariumR annotation dashboard"
    }
  }
  
  object_rds <- file.path(output_dir, "hervarium_dashboard_object.rds")
  rmd_file <- file.path(output_dir, "hervarium_dashboard.Rmd")
  
  saveRDS(x, object_rds)
  
  if (object_type == "comparison") {
    write_hervarium_comparison_dashboard_rmd(
      rmd_file = rmd_file,
      title = title,
      top_n = top_n,
      self_contained = self_contained
    )
  } else {
    write_hervarium_annotation_dashboard_rmd(
      rmd_file = rmd_file,
      title = title,
      top_n = top_n,
      self_contained = self_contained
    )
  }
  
  old_wd <- getwd()
  on.exit(setwd(old_wd), add = TRUE)
  setwd(output_dir)
  
  rmarkdown::render(
    input = basename(rmd_file),
    output_file = report_file,
    quiet = TRUE,
    envir = new.env(parent = globalenv())
  )
  
  message("HERVariumR dashboard written to: ", file.path(output_dir, report_file))
  
  invisible(file.path(output_dir, report_file))
}


