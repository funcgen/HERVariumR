    "  entries <- entries[entries != '' & entries != '.']",
    "  domain_types <- vapply(entries, function(e) {",
    "    parts1 <- unlist(strsplit(e, '|', fixed = TRUE))",
    "    if (length(parts1) != 2) return(NA_character_)",
    "    parts2 <- unlist(strsplit(parts1[2], ':', fixed = TRUE))",
