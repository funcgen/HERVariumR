write_hervarium_annotation_dashboard_rmd <- function(rmd_file,
                                                     title,
                                                     top_n = 25,
                                                     self_contained = TRUE) {
  
  self_contained_txt <- ifelse(self_contained, "true", "false")
  
  rmd_text <- c(
    "---",
    paste0("title: \"", title, "\""),
    "output:",
    "  html_document:",
    "    toc: true",
    "    toc_float: true",
    "    theme: flatly",
    paste0("    self_contained: ", self_contained_txt),
    "---",
    "",
    "```{r setup, include=FALSE}",
    "knitr::opts_chunk$set(echo = FALSE, warning = FALSE, message = FALSE)",
    "library(ggplot2)",
    "library(plotly)",
    "library(DT)",
    "",
    "anno <- readRDS('hervarium_dashboard_object.rds')",
    "features <- anno$features",
    "summary_table <- anno$summary",
    "stats <- anno$stats",
    "missing_ids <- anno$missing_ids",
    "top_n <- ", as.character(top_n),
    "",
    "domain_coverage_cutoff <- NA_real_",
    "",
    "if (!is.null(stats) &&",
    "    'domain_coverage_cutoff' %in% colnames(stats)) {",
    "  domain_coverage_cutoff <- stats$domain_coverage_cutoff[1]",
    "}",
    "",
    "domain_threshold_text <- ifelse(",
    "  is.na(domain_coverage_cutoff),",
    "  'No domain coverage threshold was found in the object. Domain summaries reflect the domain annotations stored in the input object.',",
    "  paste0(",
    "    'Internal retroviral domains were considered valid only when HMM profile coverage was >= ',",
    "    domain_coverage_cutoff,",
    "    '. Domain counts, domain-class presence, domain-type summaries and conservation plots are based on this threshold.'",
    "  )",
    ")",
    "",
    "safe_dt <- function(x, page_length = 10) {",
    "  if (is.null(x) || nrow(x) == 0) {",
    "    return(htmltools::HTML('<p><em>No results available for this section.</em></p>'))",
    "  }",
    "  DT::datatable(",
    "    x,",
    "    filter = 'top',",
    "    extensions = c('Buttons'),",
    "    options = list(",
    "      pageLength = page_length,",
    "      scrollX = TRUE,",
    "      dom = 'Bfrtip',",
    "      buttons = c('copy', 'csv', 'excel')",
    "    )",
    "  )",
    "}",
    "",
    "safe_plotly <- function(p) {",
    "  if (is.null(p)) return(NULL)",
    "  plotly::ggplotly(p)",
    "}",
    "",
    "has_cols <- function(df, cols) {",
    "  !is.null(df) && all(cols %in% colnames(df))",
    "}",
    "```",
    "",
    "# Overview",
    "",
    "## Analysis settings",
    "",
    "```{r analysis-settings}",
    "htmltools::div(",
    "  style = 'padding: 12px; border-left: 5px solid #0072B2; background-color: #F2F7FB; margin-bottom: 15px;',",
    "  htmltools::strong('Domain coverage threshold: '),",
    "  htmltools::HTML(domain_threshold_text)",
    ")",
    "```",
    "",
    "## Annotation statistics",
    "",
    "```{r stats}",
    "safe_dt(stats, page_length = 5)",
    "```",
    "",
    "## Compact HERV feature table",
    "",
    "```{r features}",
    "safe_dt(features, page_length = 15)",
