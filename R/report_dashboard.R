    "",
    "```{r domain-class}",
    "domain_cols <- c('has_gag', 'has_pol', 'has_env', 'has_accessory')",
    "if (all(domain_cols %in% colnames(features))) {",
    "  domain_counts <- data.frame(",
    "    domain_class = c('gag', 'pol', 'env', 'accessory'),",
    "    n_hervs = c(",
    "      sum(features$has_gag, na.rm = TRUE),",
    "      sum(features$has_pol, na.rm = TRUE),",
    "      sum(features$has_env, na.rm = TRUE),",
    "      sum(features$has_accessory, na.rm = TRUE)",
