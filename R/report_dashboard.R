    "    a <- df$foreground_yes + pseudocount",
    "    b <- df$foreground_no + pseudocount",
    "    c <- df$background_yes + pseudocount",
    "    d <- df$background_no + pseudocount",
    "    df$odds_ratio_plot <- (a / b) / (c / d)",
    "    df$log2_or_plot <- log2(df$odds_ratio_plot)",
    "  } else {",
    "    df$log2_or_plot <- suppressWarnings(log2(df$odds_ratio))",
    "    df$log2_or_plot[is.infinite(df$log2_or_plot)] <- NA_real_",
    "  }",
    "  df",
    "}",
    "",
    "comparison_palette <- c(",
    "  'Significant enriched' = '#D55E00',",
    "  'Significant depleted' = '#0072B2',",
    "  'Not significant' = '#BDBDBD'",
    ")",
    "",
    "add_effect_category <- function(df, effect_col, padj_cutoff = 0.05) {",
    "  df$effect_category <- 'Not significant'",
    "  sig <- !is.na(df$padj) & df$padj < padj_cutoff",
    "  enriched <- !is.na(df[[effect_col]]) & df[[effect_col]] > 0",
    "  depleted <- !is.na(df[[effect_col]]) & df[[effect_col]] < 0",
    "  df$effect_category[sig & enriched] <- 'Significant enriched'",
    "  df$effect_category[sig & depleted] <- 'Significant depleted'",
    "  df$effect_category <- factor(",
    "    df$effect_category,",
    "    levels = c(",
    "      'Significant enriched',",
    "      'Significant depleted',",
    "      'Not significant'",
    "    )",
    "  )",
    "  df",
    "}",
    "",
    "plot_enrichment <- function(df, title, top_n = 25, padj_cutoff = 0.05) {",
    "  if (is.null(df) || nrow(df) == 0) return(NULL)",
    "  df <- df[!is.na(df$p_value), , drop = FALSE]",
    "  if (nrow(df) == 0) return(NULL)",
    "  df <- add_plot_log2_or(df)",
    "  df <- add_effect_category(df, effect_col = 'log2_or_plot', padj_cutoff = padj_cutoff)",
    "  df <- df[order(df$p_value), , drop = FALSE]",
    "  df <- head(df, top_n)",
    "  df$feature <- factor(df$feature, levels = rev(df$feature))",
    "  p <- ggplot(df, aes(x = feature, y = log2_or_plot, fill = effect_category,",
    "                     text = paste0(",
    "                       'Feature: ', feature,",
    "                       '<br>Direction: ', effect_category,",
    "                       '<br>Foreground: ', foreground_yes, '/', foreground_total,",
    "                       ' (', round(foreground_percent, 1), '%)',",
    "                       '<br>Background: ', background_yes, '/', background_total,",
    "                       ' (', round(background_percent, 1), '%)',",
    "                       '<br>OR: ', round(odds_ratio, 3),",
    "                       '<br>Plot log2 OR: ', round(log2_or_plot, 3),",
    "                       '<br>p-value: ', signif(p_value, 3),",
    "                       '<br>FDR: ', signif(padj, 3)",
    "                     ))) +",
    "    geom_col() +",
    "    coord_flip() +",
    "    geom_hline(yintercept = 0, linetype = 'dashed') +",
    "    scale_fill_manual(values = comparison_palette, drop = FALSE) +",
    "    labs(title = title, x = NULL, y = 'log2 odds ratio', fill = NULL) +",
    "    theme_bw() +",
    "    theme(legend.position = 'top')",
    "  plotly::ggplotly(p, tooltip = 'text')",
    "}",
    "",
    "plot_numeric <- function(df, title, top_n = 25, padj_cutoff = 0.05) {",
    "  if (is.null(df) || nrow(df) == 0) return(NULL)",
    "  df <- df[!is.na(df$p_value), , drop = FALSE]",
    "  if (nrow(df) == 0) return(NULL)",
    "  df <- add_effect_category(df, effect_col = 'delta_median', padj_cutoff = padj_cutoff)",
    "  df <- df[order(df$p_value), , drop = FALSE]",
    "  df <- head(df, top_n)",
    "  df$feature <- factor(df$feature, levels = rev(df$feature))",
    "  p <- ggplot(df, aes(x = feature, y = delta_median, fill = effect_category,",
    "                     text = paste0(",
    "                       'Feature: ', feature,",
    "                       '<br>Direction: ', effect_category,",
    "                       '<br>Foreground median: ', round(foreground_median, 3),",
    "                       '<br>Background median: ', round(background_median, 3),",
    "                       '<br>Delta median: ', round(delta_median, 3),",
    "                       '<br>p-value: ', signif(p_value, 3),",
    "                       '<br>FDR: ', signif(padj, 3)",
    "                     ))) +",
    "    geom_col() +",
    "    coord_flip() +",
    "    geom_hline(yintercept = 0, linetype = 'dashed') +",
    "    scale_fill_manual(values = comparison_palette, drop = FALSE) +",
    "    labs(title = title, x = NULL, y = 'Delta median', fill = NULL) +",
    "    theme_bw() +",
    "    theme(legend.position = 'top')",
    "  plotly::ggplotly(p, tooltip = 'text')",
    "}",
    "```",
    "",
    "# Overview",
    "",
    "## Analysis settings",
    "",
    "```{r analysis-settings}",
    "htmltools::div(",
    "  style = 'padding: 12px; border-left: 5px solid #0072B2; background-color: #F2F7FB; margin-bottom: 15px;',",
    "  htmltools::strong('Domain coverage threshold: '),",
    "  htmltools::HTML(domain_threshold_text)",
    ")",
    "```",
    "",
    "## Input summary",
    "",
    "```{r input-summary}",
    "safe_dt(cmp$input_summary, page_length = 5)",
    "```",
    "",
    "## Matched HERV features",
    "",
    "```{r features-table}",
    "safe_dt(features, page_length = 10)",
    "```",
    "",
    "# Core enrichment",
    "",
    "## Binary feature enrichment",
    "",
    "```{r binary-feature-plot}",
    "plot_enrichment(cmp$binary_features, 'Binary feature enrichment', top_n = 50, padj_cutoff = 0.05)",
    "```",
    "",
    "```{r binary-feature-table}",
    "safe_dt(cmp$binary_features, page_length = 15)",
    "```",
    "",
    "## Numeric feature shifts",
    "",
    "```{r numeric-feature-plot}",
    "plot_numeric(cmp$numeric_features, 'Numeric feature shifts', top_n = top_n, padj_cutoff = 0.05)",
